export type UiLanguage = "zh-TW" | "en";
export type UiTheme = "light" | "dark";
export type UiDensity = "comfortable" | "compact";
export type UiDetailSurface = "dialog" | "panel";

export interface UiPreferences {
  language: UiLanguage;
  theme: UiTheme;
  density: UiDensity;
  detailSurface: UiDetailSurface;
}

export const UI_PREFERENCES_KEY = "second-brain.uiPreferences";

export const DEFAULT_UI_PREFERENCES: UiPreferences = {
  language: "zh-TW",
  theme: "light",
  density: "comfortable",
  detailSurface: "dialog",
};

export function normalizeUiPreferences(value: unknown): UiPreferences {
  if (!value || typeof value !== "object") return DEFAULT_UI_PREFERENCES;
  const candidate = value as Partial<UiPreferences>;
  if (
    (candidate.language !== "zh-TW" && candidate.language !== "en")
    || (candidate.theme !== "light" && candidate.theme !== "dark")
  ) return DEFAULT_UI_PREFERENCES;
  return {
    language: candidate.language,
    theme: candidate.theme,
    density: candidate.density === "compact" ? "compact" : "comfortable",
    detailSurface: candidate.detailSurface === "panel" ? "panel" : "dialog",
  };
}

